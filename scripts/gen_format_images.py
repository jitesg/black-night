"""Regenerate src/lib/formatImagesData.ts from assets/format-images/*.png.
Add a picture: put the PNG in assets/format-images/ and its name in NAMES, then run
  python3 scripts/gen_format_images.py
"""
import base64
from PIL import Image

NAMES = {
    # name used after [[चित्र]]  : file, comment
    'फोटो-लाश-पुरुष': ('photo_lash_male.png', 'फोटो लाश — पुरुष शरीर (आगे / पीछे), owner supplied'),
    'फोटो-लाश-महिला': ('photo_lash_female.png', 'फोटो लाश — महिला शरीर (आगे / पीछे), owner supplied'),
}

rows = []
for name, (file, note) in NAMES.items():
    p = f'assets/format-images/{file}'
    w, h = Image.open(p).size
    b = base64.b64encode(open(p, 'rb').read()).decode()
    rows.append(f"  // {note}\n  '{name}': {{ w: {w}, h: {h}, png: '{b}' }},")
open('src/lib/formatImagesData.ts', 'w').write(
    "/**\n * Pictures used by formats through the [[चित्र]] mark — GENERATED by scripts/gen_format_images.py\n"
    " * from assets/format-images/ (do not edit by hand). Base64 so print, Word and the editor need no file access.\n */\n"
    "export const FORMAT_IMAGE_DATA: Record<string, { png: string; w: number; h: number }> = {\n"
    + "\n".join(rows) + "\n};\n")
print('ok', list(NAMES))
