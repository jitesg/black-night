def by_type(k):
    """Fallback by field type (used only when nothing better is written)."""
    t = k.get('field_type')
    if t == 'checkbox':
        return 'टिक करें तो यह हिस्सा पत्र में जुड़ेगा; ज़रूरत न हो तो खाली छोड़ें'
    if t == 'date':
        return 'कैलेंडर से तारीख चुनें — पत्र में 12.11.2026 की तरह छपेगी'
    if t == 'dropdown':
        return 'जो सही हो वह बटन दबाकर चुनें — पत्र के शब्द उसी के हिसाब से बदलते हैं'
    return None
