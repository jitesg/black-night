def hint(f, k):
    n = k['key_name']; fid = f['id']
    s = SPECIFIC.get(fid, {})
    if n in s:
        return s[n]
    if fid == 'sys-fmt-pp-janta-darshan-aakhya':
        m = re.fullmatch(r'p(\d+)(Text)?', n)
        if m:
            return ('इस बिन्दु पर क्या कार्यवाही हुई, छोटे वाक्य में (हल्के रंग वाला सिर्फ़ उदाहरण) — खाली छोड़ें तो सिर्फ़ ✓ छपेगा' if m.group(2)
                    else 'यह बिन्दु लागू हो तो टिक करें — सूची में ✓ लगेगा और विवरण का बॉक्स खुलेगा')
    if n in COMMON:
        return COMMON[n]
    return _generic(k) or by_type(k)
