def wants(f):
    return f.get('format_type') in ('Case Diary', 'Narrative')

def _ph(k):
    try:
        v = json.loads(k.get('dropdown_options') or '')
        return v.get('placeholder') if isinstance(v, dict) else None
    except Exception:
        return None

def _generic(k):
    """Label + example (+ optional note) for plain data boxes."""
    lab = re.sub(r'\s*\((वैकल्पिक[^)]*|जैसे:[^)]*)\)', '', k['label']).strip(' —-')
    lab = re.sub(r'^(व्यक्ति|चिकित्सक) \d — ', '', lab)
    lab = re.sub(r'^\d+[^\s.]*\.\s*', '', lab)  # "1ए. " / "12. " point numbers
    ph = _ph(k)
    opt = 'वैकल्पिक' in k['label']
    t = k.get('field_type')
    if t in ('text', 'number', 'decimal', 'multiline'):
        if re.search(r'दिनांक|तारीख|Date|from|to\b|upto|Validity|expire|Inspected', k['label']) and t == 'text':
            s = f'{lab}: तारीख बिंदु लगाकर लिखें' + (f' — {ph}' if ph else ', जैसे: 05.07.2025')
        else:
            s = f'{lab} लिखें' + (f' — {ph}' if ph else '')
        if opt:
            s += ' (न हो तो खाली छोड़ें)'
        return s
    return None

